/************************************************************************/
/* 1. CTE (Common Table Expression)                                     */
/************************************************************************/

-- ▶ 개념
-- WITH 절을 사용하여 임시 결과 집합을 정의하는 방법
-- 복잡한 쿼리를 단계별로 분리하여 가독성을 높임
-- 쿼리 실행 중에만 존재하며, 실행 후 사라짐
-- 같은 결과를 여러 번 재사용할 때 유용

-- ▶ 기본 구조
-- WITH CTE명 AS (
--     SELECT ...
-- )
-- SELECT ... FROM CTE명;


/************************************************************************/
/* 2. LEFT JOIN                                                         */
/************************************************************************/

-- ▶ 개념
-- 왼쪽(기준) 테이블의 모든 행을 유지하면서
-- 오른쪽 테이블의 일치하는 데이터를 붙임
-- 오른쪽 테이블에 일치하는 데이터가 없으면 NULL로 채움
-- INNER JOIN과 달리 구매 이력 없는 회원도 포함됨

-- ▶ INNER JOIN vs LEFT JOIN 차이
-- INNER JOIN: 두 테이블 모두 데이터 있는 것만 출력
-- LEFT JOIN : 왼쪽 테이블 전체 + 오른쪽 일치하는 데이터

/************************************************************************/
/* 3. SELF JOIN                                                         */
/************************************************************************/

-- ▶ 개념
-- 같은 테이블을 두 번 JOIN하는 방법
-- 테이블 내에서 행끼리 비교할 때 사용
-- 반드시 별칭(AS)을 다르게 지정해야 함
-- 계층 구조, 이전/다음 값 비교 등에 활용


/************************************************************************/
/* 4. 쿼리 구조화                                                        */
/************************************************************************/

-- ▶ 개념
-- 복잡한 쿼리를 단계별로 나누어 작성하는 방법
-- CTE를 활용하여 각 단계를 명확히 구분
-- 가독성, 유지보수성, 재사용성 향상

-- ▶ SQL 실행 순서
-- FROM → WHERE → GROUP BY → HAVING → SELECT → ORDER BY

-- ▶ 쿼리 구조화 원칙
-- 1. 데이터 준비 (FROM + JOIN)
-- 2. 필터링 (WHERE)
-- 3. 집계 (GROUP BY + 집계함수)
-- 4. 집계 후 필터 (HAVING)
-- 5. 출력 (SELECT)
-- 6. 정렬 (ORDER BY)

--   - CTE로 단계 분리
--   - FROM → WHERE → GROUP BY → HAVING → SELECT → ORDER BY 순서
--   - 가독성과 유지보수성 향상
--   - 복잡한 조건은 CTE로 분리 후 JOIN 또는 IN으로 연결
